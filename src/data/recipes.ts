export function isRecipeUnlocked(recipe: Recipe, state: GameState): boolean {
  if (state.level < recipe.unlockLevel) return false;
  if (!recipe.unlockQuestId) return true;
  const q = state.quests.find((item) => item.id === recipe.unlockQuestId);
  return Boolean(q?.claimed);
}

export function getMasteryNextTarget(cookCount: number): number {
  if (cookCount < 3) return 3;
  if (cookCount < 10) return 10;
  if (cookCount < 25) return 25;
  return 25;
}

export function getRecipeById(id: string | null): Recipe | undefined {
  if (!id) return undefined;
  return RECIPES.find((r) => r.id === id);
}

export function getMasteryStars(cookCount: number): number {
  if (cookCount >= 25) return 3;
  if (cookCount >= 10) return 2;
  if (cookCount >= 3) return 1;
  return 0;
}
